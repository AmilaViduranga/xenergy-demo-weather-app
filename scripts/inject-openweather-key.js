#!/usr/bin/env node
/**
 * Writes src/environments/api-key.ts from OPENWEATHER_API_KEY or a local .env file.
 * Keeps the API key out of git while still allowing local/CI/Vercel builds.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const envPath = path.join(root, '.env');
const outPath = path.join(root, 'src', 'environments', 'api-key.ts');

function readDotEnv(filePath) {
  if (!fs.existsSync(filePath)) {
    return {};
  }

  return Object.fromEntries(
    fs
      .readFileSync(filePath, 'utf8')
      .split('\n')
      .map((line) => line.trim())
      .filter((line) => line && !line.startsWith('#') && line.includes('='))
      .map((line) => {
        const index = line.indexOf('=');
        const key = line.slice(0, index).trim();
        const value = line.slice(index + 1).trim().replace(/^['"]|['"]$/g, '');
        return [key, value];
      }),
  );
}

const fromFile = readDotEnv(envPath);
const apiKey = process.env.OPENWEATHER_API_KEY || fromFile.OPENWEATHER_API_KEY || '';

fs.writeFileSync(
  outPath,
  `/** Generated by scripts/inject-openweather-key.js — do not commit secrets. */\n` +
    `export const openWeatherApiKey = ${JSON.stringify(apiKey)};\n`,
);

if (!apiKey) {
  console.warn(
    '[inject-openweather-key] OPENWEATHER_API_KEY is empty. Set it in .env or CI/Vercel secrets.',
  );
} else {
  console.log('[inject-openweather-key] Wrote src/environments/api-key.ts');
}
